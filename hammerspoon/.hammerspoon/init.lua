hs.hotkey.bind({"cmd"}, "`", function()
    local app = hs.application.get("com.mitchellh.ghostty")

    if not app then
        hs.application.launchOrFocusByBundleID("com.mitchellh.ghostty")
        return
    end

    if app:isFrontmost() then
        app:hide()
    else
        app:activate(true)
    end
end)